const root = join(import.meta.dirname, '..');
const files = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard', 'test'], { cwd: root, encoding: 'utf8' })
  .split('\0')
  .filter((f) => isTest(f) && existsSync(join(root, f)) && f !== 'test/harness-copies.test.ts');

for (const [name, fam] of Object.entries(FAMILIES)) {
  test(`${name}: no new copy of the shared harness`, () => {
    const extra: string[] = [];
    for (const f of files) {
      const n = readFileSync(join(root, f), 'utf8').split('\n').filter(fam.copy).length;
      const kept = KEPT[name][f] ?? 0;
      if (n > kept) extra.push(`${f}: ${n} copies${kept ? ` (${kept} kept)` : ''}`);
    }
    assert.deepEqual(extra, [], `Use ${fam.use} instead of a copy. A copy that truly differs goes in KEPT with a why.`);
  });
  test(`${name}: a planted copy is found`, () => {
    for (const p of fam.planted) assert.equal(p.split('\n').filter(fam.copy).length, 1, p);
  });
}
